"""Bake the complete pinned Tabler catalog into embedded PNG pages and a name index.

Development only: pip install CairoSVG==2.8.2 Pillow
The source archive is vendored; normal C builds require no Python or downloads.
"""
from pathlib import Path
import io
import json
import tarfile
from collections import Counter
import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/tabler-icons/sources.tar.gz'
OUTPUT = ROOT / 'lib/pengui/src/rendering'
SIZE = 64
PER_ROW = 4
PER_PAGE = PER_ROW * PER_ROW


def sources():
    result = []
    with tarfile.open(SOURCE, 'r:gz') as archive:
        for member in archive:
            if not member.isfile():
                continue
            variant, filename = member.name.split('/')
            if variant not in ('outline', 'filled') or not filename.endswith('.svg'):
                raise ValueError(member.name)
            stem = filename[:-4]
            key = stem if variant == 'outline' else 'filled/' + stem
            result.append((key, archive.extractfile(member).read()))
    return sorted(result)


def main():
    icons = sources()
    if len({name for name, _ in icons}) != len(icons):
        raise ValueError('duplicate icon names')
    catalog, pages, payload = [], [], bytearray()
    for start in range(0, len(icons), PER_PAGE):
        page = Image.new('LA', (SIZE * PER_ROW,) * 2, (255, 0))
        for slot, (name, source) in enumerate(icons[start:start + PER_PAGE]):
            png = cairosvg.svg2png(bytestring=source, output_width=SIZE, output_height=SIZE)
            alpha = Image.open(io.BytesIO(png)).convert('RGBA').getchannel('A')
            mask = Image.new('LA', (SIZE, SIZE), (255, 0))
            mask.putalpha(alpha)
            page.paste(mask, ((slot % PER_ROW) * SIZE, (slot // PER_ROW) * SIZE))
            catalog.append((name, len(pages), slot))
        buffer = io.BytesIO()
        page.save(buffer, format='PNG', optimize=True)
        data = buffer.getvalue()
        pages.append((len(payload), len(data)))
        payload.extend(data)
    (OUTPUT / 'tabler_atlas.bin').write_bytes(payload)
    lines = ['/* Generated by tools/generate_tabler_icons.py; Tabler Icons, MIT. */',
             '#ifndef PUI_TABLER_ATLAS_H', '#define PUI_TABLER_ATLAS_H',
             'static const struct { const char *name; unsigned page, slot; } tabler_catalog[] = {']
    for name, page, slot in catalog:
        lines.append(f'    {{{json.dumps(name)}, {page}, {slot}}},')
    lines.extend(['};', 'static const struct { unsigned offset, length; } tabler_pages[] = {'])
    for offset, length in pages:
        lines.append(f'    {{{offset}, {length}}},')
    lines.extend(['};', '#endif', ''])
    (OUTPUT / 'tabler_atlas.h').write_text('\n'.join(lines))
    (ROOT / 'third_party/tabler-icons/catalog.txt').write_text(
        '# Tabler Icons v3.49.0 — all available YAML names\n' +
        '\n'.join('tabler:' + name for name, _ in icons) + '\n')
    counts = Counter('filled' if name.startswith('filled/') else 'outline' for name, _ in icons)
    print(f'{len(icons)} icons: {dict(counts)}; {len(pages)} pages; {len(payload)} PNG bytes', flush=True)


if __name__ == '__main__':
    main()
