"""Bake the vendored Tabler outline selection into tintable 64px alpha masks.

Development only: pip install Pillow svgpathtools
To add an icon, place its unmodified SVG from the pinned upstream revision in
third_party/tabler-icons/icons/ and run this script. Normal C builds use the
checked-in result and need neither Python packages nor network access.
"""
from pathlib import Path
import json
import math
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw
from svgpathtools import svg2paths

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/tabler-icons/icons'
OUTPUT = ROOT / 'lib/pengui/src/rendering/tabler_atlas.h'
SIZE = 64
SUPERSAMPLE = 4


def rasterize(path):
    root = ET.parse(path).getroot()
    if root.get('viewBox') != '0 0 24 24':
        raise ValueError(f'{path}: expected Tabler 24x24 viewBox')
    scale = SIZE * SUPERSAMPLE / 24
    stroke = float(root.get('stroke-width', 2)) * scale
    image = Image.new('L', (SIZE * SUPERSAMPLE,) * 2)
    draw = ImageDraw.Draw(image)
    paths, attributes = svg2paths(str(path))
    for curve, attr in zip(paths, attributes):
        if attr.get('stroke') == 'none':
            continue
        for subpath in curve.continuous_subpaths():
            points = []
            for segment in subpath:
                count = max(1, math.ceil(segment.length() * 6))
                for step in range(count):
                    point = segment.point(step / count)
                    points.append((point.real * scale, point.imag * scale))
            if not subpath:
                continue
            point = subpath[-1].end
            points.append((point.real * scale, point.imag * scale))
            draw.line(points, fill=255, width=round(stroke), joint='curve')
            # All selected upstream outlines use rounded caps and joins.
            radius = stroke / 2
            for x, y in points:
                draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill=255)
    return image.resize((SIZE, SIZE), Image.Resampling.LANCZOS).tobytes()


def runs(pixels):
    result = []
    for value in pixels:
        if result and result[-1] == value and result[-2] < 255:
            result[-2] += 1
        else:
            result.extend((1, value))
    return result


def main():
    data, catalog = [], []
    for path in sorted(SOURCE.glob('*.svg')):
        encoded = runs(rasterize(path))
        catalog.append((path.stem, len(data), len(encoded)))
        data.extend(encoded)
    lines = ['/* Generated by tools/generate_tabler_icons.py; Tabler Icons, MIT. */',
             '#ifndef PUI_TABLER_ATLAS_H', '#define PUI_TABLER_ATLAS_H',
             'static const unsigned char tabler_runs[] = {']
    for start in range(0, len(data), 32):
        lines.append('    ' + ', '.join(map(str, data[start:start + 32])) + ',')
    lines.extend(['};', 'static const struct { const char *name; unsigned offset, length; } tabler_catalog[] = {'])
    for name, offset, length in catalog:
        lines.append(f'    {{{json.dumps(name)}, {offset}, {length}}},')
    lines.extend(['};', '#endif', ''])
    OUTPUT.write_text('\n'.join(lines))
    print(f'Generated {len(catalog)} Tabler icons ({len(data)} encoded bytes)')


if __name__ == '__main__':
    main()
