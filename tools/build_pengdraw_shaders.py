"""Regenerate embedded Vulkan/D3D12/Metal effect shaders; not required for normal builds."""
import argparse
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--glslang', default='glslangValidator')
    parser.add_argument('--dxc', default='dxc')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1] / 'lib/pengdraw/src/gpu/shaders'
    with tempfile.TemporaryDirectory() as tmp:
        for effect in ('shadow', 'gradient'):
            spv = Path(tmp) / (effect + '.spv')
            dxil = Path(tmp) / (effect + '.dxil')
            subprocess.run([args.glslang, '-V', '-S', 'frag', str(root / (effect + '.frag.glsl')),
                            '-o', str(spv)], check=True)
            subprocess.run([args.dxc, '-T', 'ps_6_0', '-E', 'main', '-O3',
                            str(root / (effect + '.frag.hlsl')), '-Fo', str(dxil)], check=True)
            out = '/* Generated by tools/build_pengdraw_shaders.py; edit adjacent shader sources. */\n'
            payloads = [('spirv', spv.read_bytes()), ('dxil', dxil.read_bytes()),
                        ('msl', (root / (effect + '.frag.msl')).read_bytes() + b'\0')]
            for name, data in payloads:
                out += f'static const unsigned char {effect}_{name}[] = {{\n'
                for offset in range(0, len(data), 16):
                    out += '    ' + ', '.join(f'0x{v:02x}' for v in data[offset:offset+16]) + ',\n'
                out += '};\n'
            (root / (effect + '_bytes.inc')).write_text(out)


if __name__ == '__main__':
    main()
