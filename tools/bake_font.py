"""Rebuild the embedded JetBrains Mono 2.304 atlas (requires Pillow).

The original font and its SIL Open Font License are in ui/assets.
Normal CMake builds use the generated header and do not require Python.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root / 'ui/assets/JetBrainsMono-Regular.ttf'), 13)
atlas = Image.new('L', (128, 256))
draw = ImageDraw.Draw(atlas)
for code in range(32, 256):
    if 127 <= code < 160:
        continue
    x, y = (code % 16) * 8, (code // 16) * 16
    draw.text((x, y + 12), chr(code), font=font, fill=255, anchor='ls')
data = list(atlas.tobytes())
runs = []
for value in data:
    if runs and runs[-1][1] == value and runs[-1][0] < 255:
        runs[-1][0] += 1
    else:
        runs.append([1, value])
values = [v for pair in runs for v in pair]
lines = [', '.join(map(str, values[i:i+24])) + ',' for i in range(0, len(values), 24)]
(root / 'ui/src/font_atlas.h').write_text(
    '/* Generated by tools/bake_font.py. JetBrains Mono 2.304, SIL OFL; see ui/assets/OFL.txt. */\n'
    'static const unsigned char ui_font_runs[] = {\n' + '\n'.join(lines) + '\n};\n')
